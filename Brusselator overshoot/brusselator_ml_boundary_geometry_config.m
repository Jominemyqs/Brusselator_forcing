    'source_final_label','B', ...
    'source_label_status','validated_reference_neighborhood', ...
    'rule',['for each of the first two landing-aware POD scores, use half ', ...
        'the observed range among validated forcing-generated B landings'], ...
    'padding_factor',1, ...
    'minimum_concentration',1e-6, ...
    'common_shrink_tolerance',1e-12, ...
    'maximum_shrink_iterations',60);
