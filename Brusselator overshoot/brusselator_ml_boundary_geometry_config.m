    'master_grid_size',17, ...
    'initial_seed_indices',[1,5,9,13,17], ...
    'fixed_test_indices',[3,7,11,15], ...
    'roles',{{'initial_seed','fixed_test','acquisition_pool'}}, ...
    'split_rule',['the 5-by-5 coarse subgrid is the common initial seed; ', ...
        'the interleaved 4-by-4 subgrid is a fixed untouched test set; all ', ...
        'remaining master-grid points form the acquisition pool'], ...
    'ordering',['rows of increasing alpha_2 with alternating alpha_1 ', ...
        'direction; used only for a reflection-continuity diagnostic']);
cfg.ml_boundary.reflection = struct( ...
    'canonicalizer','brusselator_reflection_canonicalize', ...
    'saved_orientations',{{'raw','reflected','feature_canonical', ...
        'serpentine_continuity'}}, ...
    'invariance_tolerance',1e-8, ...
    'continuity_interpretation',['the serpentine orientation is a diagnostic ', ...
        'on this finite grid, not a protocol-independent quotient coordinate']);
