    'exact_edge_orbit',['not loaded or used in the construction; reserved ', ...
        'for later dynamical evaluation'], ...
    'held_out_CA_region',['the lambda approximately 0.276 C--B--A interval ', ...
        'is not loaded, used for bounds, or inspected by this builder']);
cfg.ml_boundary.status = struct( ...
    'simulation_status','not_run', ...
    'outcome_label','', ...
    'meaning',['the manifest freezes candidate states and data splits only; ', ...
        'no row has an inferred or inherited PDE outcome label']);
