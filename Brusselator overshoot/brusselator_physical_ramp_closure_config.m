%   This experiment refines the actual symmetric-ramp protocol coordinate;
%   it never interpolates forcing-return states when assigning protocol
%   outcomes. Every landing state is evolved under the frozen b=10 PDE and
%   classified against the validated A/B/C/R5/R6 orbit library.

