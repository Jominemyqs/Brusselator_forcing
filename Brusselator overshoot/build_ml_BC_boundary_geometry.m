function w = spatial_weights(N,Lx)
w=(Lx/(N-1))*ones(1,N); w([1,end])=0.5*w(1);
end

function [direct,reflected] = distance_components(UA,VA,UB,VB,Lx)
w=spatial_weights(numel(UA),Lx);
energy_A=sum((UA.^2+VA.^2).*w); energy_B=sum((UB.^2+VB.^2).*w);
denominator=max(0.5*(energy_A+energy_B),eps);
direct=sqrt(sum(((UA-UB).^2+(VA-VB).^2).*w)/denominator);
reflected=sqrt(sum(((UA-fliplr(UB)).^2+(VA-fliplr(VB)).^2).*w)/denominator);
end

function value = direct_relative_distance(UA,VA,UB,VB,w)
energy_A=sum((UA.^2+VA.^2).*w); energy_B=sum((UB.^2+VB.^2).*w);
value=sqrt(sum(((UA-UB).^2+(VA-VB).^2).*w)/ ...
    max(0.5*(energy_A+energy_B),eps));
end
